import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
import { authTables } from "@convex-dev/auth/server";
const patientId = v.id("patients");
const optionalString = v.optional(v.string());
export const item = v.object({
  id: v.string(),
  exerciseId: v.id("exercises"),
  sets: v.number(),
  reps: v.number(),
  holdSec: v.number(),
  cue: v.string(),
  days: v.array(v.number()),
});
export const outcome = v.object({
  id: v.optional(v.string()),
  label: v.string(),
  measure: v.string(),
  target: v.string(),
  retestWeek: v.number(),
  doneAt: v.optional(v.number()),
});
export const phase = v.object({
  name: v.string(),
  weekStart: v.number(),
  weekEnd: v.number(),
  focus: v.string(),
  visits: v.number(),
  milestone: v.string(),
});
export default defineSchema({
  ...authTables,
  patients: defineTable({
    userId: v.optional(v.id("users")),
    name: v.string(),
    email: v.string(),
    phone: v.string(),
    stage: v.string(),
    status: v.string(),
    goal: v.string(),
    mainPain: optionalString,
    ptId: v.optional(v.id("staff")),
    closerId: v.optional(v.id("staff")),
    referredById: v.optional(patientId),
    source: v.string(),
    depositAt: v.number(),
    lastLoginAt: v.optional(v.number()),
    lastActivityAt: v.optional(v.number()),
    dischargedAt: v.optional(v.number()),
    referralToken: v.string(),
    ghlContactId: optionalString,
    ghlOpportunityId: optionalString,
    ghlDesiredStage: optionalString,
    stripeCustomerId: optionalString,
    physicianReferral: optionalString,
    physicianReferralAt: v.optional(v.number()),
    reviewConfirmedAt: v.optional(v.number()),
    painResolvedAt: v.optional(v.number()),
    archivedAt: v.optional(v.number()),
    evaluationCohort: v.optional(v.object({appointmentId:v.id('appointments'),evaluatedAt:v.number(),completedBefore:v.boolean()})),
  })
    .index("by_email", ["email"])
    .index("by_user", ["userId"])
    .index("by_ghl", ["ghlContactId"])
    .index("by_referral", ["referralToken"])
    .index("by_phone", ["phone"]),
  staff: defineTable({
    userId: v.id("users"),
    name: v.string(),
    roles: v.array(v.string()),
    photoId: v.optional(v.id("_storage")),
    active: v.boolean(),
  }).index("by_user", ["userId"]),
  appointments: defineTable({
    patientId,
    kind: v.string(),
    startsAt: v.number(),
    location: v.string(),
    status: v.string(),
    ghlAppointmentId: optionalString,
    sourceUpdatedAt: v.number(),
    revision: v.optional(v.number()),
  })
    .index("by_patient", ["patientId"])
    .index("by_ghl", ["ghlAppointmentId"]),
  payments: defineTable({
    patientId,
    kind: v.string(),
    amountCents: v.number(),
    stripeId: v.string(),
    status: v.string(),
    refundedCents: v.optional(v.number()),
    appliedToId: v.optional(v.id("plansOfCare")),
    at: v.number(),
  })
    .index("by_patient", ["patientId"])
    .index("by_stripe", ["stripeId"]),
  videos: defineTable({
    title: v.string(),
    playbackId: v.string(),
    durationSec: v.number(),
    whyLine: v.string(),
    category: v.string(),
    captionsReady: v.boolean(),
    archived: v.boolean(),
  }),
  quizzes: defineTable({
    videoId: v.id("videos"),
    questions: v.array(
      v.object({
        prompt: v.string(),
        options: v.array(v.string()),
        correctIndex: v.number(),
        jumpToSec: v.number(),
      }),
    ),
  }).index("by_video", ["videoId"]),
  sequences: defineTable({
    name: v.string(),
    active: v.boolean(),
    items: v.array(
      v.object({ videoId: v.id("videos"), dueOffsetDays: v.number() }),
    ),
  }),
  videoAssignments: defineTable({
    patientId,
    videoId: v.id("videos"),
    order: v.number(),
    dueAt: v.number(),
    unlockedAt: v.optional(v.number()),
    watchedSec: v.number(),
    lastProgressAt: v.optional(v.number()),
    completedAt: v.optional(v.number()),
    quizPassedAt: v.optional(v.number()),
  }).index("by_patient", ["patientId"]),
  plansOfCare: defineTable({
    patientId,
    goal: v.string(),
    weeks: v.number(),
    visits: v.number(),
    priceCents: v.number(),
    startDate: v.number(),
    // draft, produced, scope_confirmed, price_revealed, accepted, declined, sent_to_portal, completed
    status: v.string(),
    installments: v.boolean(),
    signedAt: v.optional(v.number()),
    signedBy: v.optional(v.id("staff")),
    acceptedAt: v.optional(v.number()),
    terms: v.optional(v.string()),
    milestones: v.optional(
      v.array(
        v.object({
          label: v.string(),
          week: v.number(),
          doneAt: v.optional(v.number()),
        }),
      ),
    ),
    // Addendum 1: the accepted proposal is the plan of care.
    templateId: v.optional(v.id("proposalTemplates")),
    authorId: v.optional(v.id("staff")),
    mainPain: optionalString,
    findings: optionalString,
    visitsPerWeek: v.optional(v.number()),
    why: optionalString,
    programmingFocus: optionalString,
    outcomes: v.optional(v.array(outcome)),
    phases: v.optional(v.array(phase)),
    included: v.optional(v.array(v.string())),
    installmentTotalCents: v.optional(v.number()),
    depositCreditCents: v.optional(v.number()),
    paymentOption: v.optional(v.union(v.literal("full"), v.literal("installments"))),
    producedAt: v.optional(v.number()),
    scopeConfirmedAt: v.optional(v.number()),
    priceRevealedAt: v.optional(v.number()),
    termsAcceptedAt: v.optional(v.number()),
    declinedAt: v.optional(v.number()),
    sentToPortalAt: v.optional(v.number()),
    declineReason: optionalString,
    declineNote: optionalString,
    version: v.optional(v.number()),
    offerVersion: v.optional(v.number()),
    installmentsApprovedBy: v.optional(v.id('staff')),
    installmentsApprovedAt: v.optional(v.number()),
    agreementId: v.optional(v.id('paymentAgreements')),
    revisions: v.optional(
      v.array(
        v.object({
          version: v.number(),
          at: v.number(),
          authorId: v.id("staff"),
          authorName: v.string(),
          note: v.string(),
          previous: v.any(),
        }),
      ),
    ),
  }).index("by_patient", ["patientId"]),
  proposalTemplates: defineTable({
    name: v.string(),
    condition: v.string(),
    weeks: v.number(),
    visitsPerWeek: v.number(),
    why: v.string(),
    programmingFocus: v.string(),
    outcomes: v.array(outcome),
    phases: v.array(phase),
    included: v.array(v.string()),
    priceCents: v.number(),
    active: v.boolean(),
  }),
  exercises: defineTable({
    name: v.string(),
    videoId: v.optional(v.id("videos")),
    defaultCue: v.string(),
    tags: v.array(v.string()),
    archived: v.boolean(),
  }),
  programs: defineTable({
    patientId,
    version: v.number(),
    active: v.boolean(),
    publishedAt: v.number(),
    items: v.array(item),
  }).index("by_patient", ["patientId"]),
  sessionLogs: defineTable({
    patientId,
    programId: v.id("programs"),
    programVersion: v.number(),
    date: v.string(),
    startedAt: v.number(),
    doneItemIds: v.array(v.string()),
    feel: optionalString,
    note: optionalString,
    completedAt: v.optional(v.number()),
  }).index("by_patient", ["patientId"]),
  sessionAssignments: defineTable({
    patientId,
    programId: v.id("programs"),
    date: v.string(),
    itemIds: v.array(v.string()),
  })
    .index("by_patient", ["patientId"])
    .index("by_date", ["date"]),
  measurements: defineTable({
    patientId,
    label: v.string(),
    unit: v.string(),
    value: v.union(v.number(), v.string()),
    kind: v.string(),
    takenAt: v.number(),
  }).index("by_patient", ["patientId"]),
  clinicalNotes: defineTable({
    patientId,
    appointmentId: v.optional(v.id("appointments")),
    kind: v.string(),
    subjective: v.string(),
    objective: v.string(),
    assessment: v.string(),
    plan: v.string(),
    icd10: v.array(v.string()),
    cpt: v.array(v.string()),
    services: v.optional(v.array(v.object({date:v.string(),code:v.string(),units:v.number(),feeCents:v.number(),modifiers:v.string()}))),
    authorId: v.id("staff"),
    signedAt: v.optional(v.number()),
    addenda: v.array(
      v.object({ body: v.string(), at: v.number(), authorId: v.id("staff") }),
    ),
  }).index("by_patient", ["patientId"]),
  visitSummaries: defineTable({
    patientId,
    appointmentId: v.optional(v.id("appointments")),
    body: v.string(),
    authorId: v.id("staff"),
    at: v.number(),
  }).index("by_patient", ["patientId"]),
  messages: defineTable({
    patientId,
    senderKind: v.string(),
    senderId: v.string(),
    senderName: v.string(),
    body: v.string(),
    painFlag: v.boolean(),
    at: v.number(),
  }).index("by_patient", ["patientId"]),
  messageReads: defineTable({
    patientId,
    userId: v.id("users"),
    readAt: v.number(),
  }).index("by_patient", ["patientId"]),
  referrals: defineTable({
    referrerId: patientId,
    friendName: v.string(),
    friendContact: v.string(),
    referredPatientId: v.optional(patientId),
    status: v.string(),
    at: v.number(),
  })
    .index("by_referrer", ["referrerId"])
    .index("by_contact", ["friendContact"]),
  creditLedger: defineTable({
    patientId,
    amountCents: v.number(),
    reason: v.string(),
    referralId: v.optional(v.id("referrals")),
    appliedToPaymentId: optionalString,
    key: v.string(),
    at: v.number(),
  })
    .index("by_patient", ["patientId"])
    .index("by_key", ["key"]),
  saves: defineTable({
    patientId,
    rule: v.string(),
    level: v.string(),
    play: v.string(),
    ownerRole: v.string(),
    ownerId: v.optional(v.id("staff")),
    dueAt: v.number(),
    doneAt: v.optional(v.number()),
    outcome: optionalString,
    conditionActive: v.boolean(),
    attempts: v.array(
      v.object({ at: v.number(), outcome: v.string(), actorId: v.string() }),
    ),
  }).index("by_patient", ["patientId"]),
  events: defineTable({
    patientId,
    type: v.string(),
    data: v.any(),
    at: v.number(),
  }).index("by_patient", ["patientId"]),
  documents: defineTable({
    patientId,
    kind: v.string(),
    fileId: v.id("_storage"),
    name: v.string(),
    at: v.number(),
    staffOnly: v.boolean(),
    key: v.optional(v.string()),
    planId: v.optional(v.id('plansOfCare')),
    planVersion: v.optional(v.number()),
    documentState: optionalString,
  })
    .index("by_patient", ["patientId"])
    .index("by_key", ["key"]),
  auditLog: defineTable({
    actorId: v.string(),
    action: v.string(),
    targetTable: v.string(),
    targetId: v.string(),
    at: v.number(),
  }).index("by_target", ["targetTable", "targetId"]),
  settings: defineTable({ key: v.string(), value: v.any() }).index("by_key", [
    "key",
  ]),
  webhookEvents: defineTable({
    provider: v.string(),
    key: v.string(),
    payload: v.any(),
    status: v.string(),
    attempts: v.number(),
    receivedAt: v.number(),
    processedAt: v.optional(v.number()),
    error: optionalString,
  }).index("by_key", ["key"]),
  integrationJobs: defineTable({
    patientId: v.optional(patientId),
    kind: v.string(),
    key: v.string(),
    payload: v.any(),
    status: v.string(),
    attempts: v.number(),
    createdAt: v.number(),
    nextAt: v.number(),
    error: optionalString,
    failureCategory: optionalString,
    history:v.optional(v.array(v.object({at:v.number(),outcome:v.string()}))),
  })
    .index("by_key", ["key"])
    .index("by_status", ["status"]),
  notificationDeliveries: defineTable({
    patientId,
    key: v.string(),
    channel: v.string(),
    template: v.string(),
    scheduledAt: v.number(),
    status: v.string(),
    sentAt: v.optional(v.number()),
  })
    .index("by_key", ["key"])
    .index("by_patient", ["patientId"]),
  installmentSchedules: defineTable({
    patientId,
    planId: v.id("plansOfCare"),
    amountCents: v.number(),
    dueAt: v.number(),
    sequence: v.number(),
    status: v.string(),
    stripeId: optionalString,
  })
    .index("by_patient", ["patientId"])
    .index("by_plan", ["planId"]),
  memberships: defineTable({
    patientId,
    status: v.string(),
    priceCents: v.number(),
    terms: v.string(),
    acceptedAt: v.number(),
    paymentMethodId: optionalString,
    stripeSubscriptionId: optionalString,
    startedAt: v.optional(v.number()),
    cancelAt: v.optional(v.number()),
      lastStripeEventAt: v.optional(v.number()),
  })
    .index("by_patient", ["patientId"])
    .index("by_stripe", ["stripeSubscriptionId"]),
  loginRequests: defineTable({ emailHash: v.string(), at: v.number() }).index(
    "by_email",
    ["emailHash"],
  ),
    checkoutAttempts: defineTable({
      patientId, targetId:v.string(), kind:v.string(), expiresAt:v.number(),
      sessionId:optionalString, previousSessionId:optionalString,
      agreementId:v.optional(v.id('paymentAgreements')), status:optionalString,
    }).index('by_target',['targetId']),
    presentationSessions:defineTable({sessionId:v.id('authSessions'),patientId,staffId:v.id('staff'),createdAt:v.number()}).index('by_session',['sessionId']),
    paymentAgreements:defineTable({patientId,planId:v.id('plansOfCare'),offerVersion:v.number(),planVersion:v.number(),priceCents:v.number(),depositCreditCents:v.number(),deposits:v.array(v.object({id:v.id('payments'),amountCents:v.number()})),option:v.union(v.literal('full'),v.literal('installments')),startDate:v.number(),charges:v.array(v.object({amountCents:v.number(),dueAt:v.number()})),totalCents:v.number(),terms:v.string(),acceptedAt:v.number(),acceptedBy:v.id('users'),installmentsApprovedBy:v.optional(v.id('staff')),status:v.string()}).index('by_patient',['patientId']).index('by_plan',['planId']),
    planVersions:defineTable({patientId,planId:v.id('plansOfCare'),version:v.number(),state:v.string(),snapshot:v.any(),at:v.number(),key:v.string()}).index('by_patient',['patientId']).index('by_key',['key']),
});
